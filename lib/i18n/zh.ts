// Widen string-literal types so other locales can supply their own strings
// while keeping the structural shape (keys + function signatures) locked in.
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends (...args: infer A) => infer R
        ? (...args: A) => Widen<R>
        : { [K in keyof T]: Widen<T[K]> };

export type ZhMessages = Widen<typeof zhMessages>;
